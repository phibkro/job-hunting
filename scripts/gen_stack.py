#!/usr/bin/env python3
"""Build a vertical stack PDF per job listing: annonseside (status + full ad
text) -> CV -> cover letter.

Sources of truth (never duplicated):
  intake/*.json          NAV feed snapshots (ad found here by uuid prefix)
  listings/<slug>.json   per-listing status/profile card (hand/agent edited)
  src/cv*.typ            CV variants
  src/cover-*.typ        letters

Output: dist/stacks/<slug>.pdf   (merged via qpdf)

Usage:  python3 scripts/gen_stack.py <slug> [...]
"""

import html
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INTAKE_GLOB = "intake/*.json"
LISTINGS_DIR = ROOT / "listings"
DIST_STACKS = ROOT / "dist" / "stacks"

TYPST_ESCAPES = {
    "\\": "\\\\",
    "#": "\\#",
    "$": "\\$",
    "*": "\\*",
    "_": "\\_",
    "`": "\\`",
    "@": "\\@",
    "<": "\\<",
    ">": "\\>",
    "[": "\\[",
    "]": "\\]",
}


def esc(s: str) -> str:
    return "".join(TYPST_ESCAPES.get(c, c) for c in s)


def find_ad(uuid_prefix: str) -> dict | None:
    for path in sorted(ROOT.glob(INTAKE_GLOB)):
        for item in json.loads(path.read_text()):
            if item["uuid"].startswith(uuid_prefix):
                return item
    return None


def html_to_text(raw: str) -> str:
    """Crude but readable HTML->plain-text for ad bodies."""
    s = raw
    s = re.sub(r"(?i)<(br|/p|/div|/h[1-6]|/li|/tr)[^>]*>", "\n", s)
    s = re.sub(r"(?i)<li[^>]*>", "\n• ", s)
    s = re.sub(r"(?i)<h([1-3])[^>]*>", lambda m: "\n" + "=" * int(m.group(1)) + " ", s)
    s = re.sub(r"<[^>]+>", "", s)
    s = html.unescape(s)
    s = re.sub(r"[ \t]+", " ", s)
    s = re.sub(r"\n\s+\n", "\n\n", s)
    s = re.sub(r"\n{3,}", "\n\n", s)
    return s.strip()


def build_annonse_typ(card: dict, ad: dict) -> str:
    contacts = "\n".join(
        f"- {esc(p.get('name', '?'))}"
        + (f", {esc(p['title'])}" if p.get("title") else "")
        + (f" — {esc(p['email'])}" if p.get("email") else "")
        + (f" — {esc(p['phone'])}" if p.get("phone") else "")
        for p in ad.get("contactList", [])
    ) or "- (ingen oppgitt)"
    loc = ", ".join(
        f"{loc_item.get('city', '')} {loc_item.get('postalCode', '')}".strip()
        for loc_item in ad.get("workLocations", [])
    )
    body = html_to_text(ad.get("description", ""))

    def link_row(label, url):
        u = esc(url)
        return f'*{label}:* #link("{u}")[{u}]'

    def row(label, val):
        return f"*{label}:* {val}"

    meta = " \\\\\n".join(
        [
            row("Stilling", esc(ad.get("title", "?"))),
            row("Arbeidsgiver", esc(ad.get("employer", {}).get("name", "?"))),
            row("Sektor / omfang", f"{esc(ad.get('sector', '?'))} / {esc(ad.get('extent', '?'))}, {esc(ad.get('engagementtype', '?'))}"),
            row("Sted", esc(loc)),
            row("Frist", esc(str(ad.get("applicationDue", ad.get("expires", "?")))[:10])),
            link_row("Søk her", ad.get("applicationUrl") or ad.get("sourceurl") or ad.get("link", "?")),
            link_row("NAV-lenke", ad.get("link", "")),
        ]
    )

    status_rows = "\n".join(f"- *{esc(k)}:* {esc(v)}" for k, v in [
        ("Stage", card.get("stage", "Todo")),
        ("Neste handling", card.get("next_action", "")),
        ("Vurdering", card.get("verdict", "")),
        ("Lønn", card.get("salary", "(uoppgitt)")),
    ] if v)

    return f"""// AUTOGENERATED by scripts/gen_stack.py — edit listings/{card['slug']}.json instead
#import "_lib.typ": *

#show: cv.with(
  subtitle: [{esc(card.get('company', ''))} — applikasjons-stack],
  intro: [],
)

#section[Status]
{status_rows}

#section[Nøkkelfakta]
#grid(columns: (auto, 1fr), column-gutter: 1em, align: (right, left))[
{meta}
]

#section[Kontakt]
{contacts}

#section[Annonse]
#block(above: 0.9em, below: 0.9em)[
#text(size: 9pt)[
{esc(body)}
]]
"""


def run(cmd: list[str]) -> None:
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"command failed: {' '.join(cmd)}\n{r.stdout}\n{r.stderr}")


def build(slug: str) -> Path | None:
    card_path = LISTINGS_DIR / f"{slug}.json"
    if not card_path.exists():
        print(f"? {slug}: ingen listings/{slug}.json — hopper over")
        return None
    card = json.loads(card_path.read_text())
    ad = find_ad(card["uuid"])
    if not ad:
        raise SystemExit(f"{slug}: fant ikke annonsen i intake/ (uuid {card['uuid']})")

    DIST_STACKS.mkdir(parents=True, exist_ok=True)
    parts: list[Path] = []

    annonse_typ = ROOT / "src" / f"_annonse-{slug}.typ"
    annonse_pdf = DIST_STACKS / f"_annonse-{slug}.pdf"
    annonse_typ.write_text(build_annonse_typ(card, ad))
    run(["typst", "compile", str(annonse_typ), str(annonse_pdf)])
    parts.append(annonse_pdf)
    annonse_typ.unlink(missing_ok=True)

    cv_name = card.get("cv")
    if cv_name and (ROOT / "src" / f"{cv_name}.typ").exists():
        cv_pdf = DIST_STACKS / f"_cv-{slug}.pdf"
        run(["typst", "compile", str(ROOT / "src" / f"{cv_name}.typ"), str(cv_pdf)])
        parts.append(cv_pdf)

    cover_name = card.get("cover")
    if cover_name and (ROOT / "src" / f"{cover_name}.typ").exists():
        cover_pdf = DIST_STACKS / f"_cover-{slug}.pdf"
        run(["typst", "compile", str(ROOT / "src" / f"{cover_name}.typ"), str(cover_pdf)])
        parts.append(cover_pdf)

    out = DIST_STACKS / f"{slug}.pdf"
    args = ["qpdf", "--empty", "--pages"]
    args += [str(p) for p in parts]
    args += ["--", str(out)]
    run(args)
    for p in parts:
        p.unlink()
    n_pages = len(re.findall(rb"/Type\s*/Page[^s]", out.read_bytes()))
    print(f"✓ dist/stacks/{slug}.pdf  ({n_pages} sider)")
    return out


if __name__ == "__main__":
    slugs = sys.argv[1:] or [p.stem for p in LISTINGS_DIR.glob("*.json")]
    built = [build(s) for s in slugs]
    if not any(built):
        raise SystemExit("ingen stacks bygget")
