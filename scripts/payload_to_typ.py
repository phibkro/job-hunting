#!/usr/bin/env python3
"""Render a career-ops CV payload (JSON) with this repo's Typst CV template.

career-ops does the tailoring and fact gates and writes a payload JSON
(candidate, summary, competencies, experience, projects, education, skills).
This script turns that payload into src/cv-<slug>.typ using the helpers in
src/_lib.typ and the header layout of src/cv-fullstack.typ (photo, name,
title, contact line), compiles it, and enforces a page budget.

Fitting is typographic only: it steps font size, leading and margins down a
fixed ladder. It never drops or rewrites content. If the CV still overflows
at the last step, it exits non-zero and says so, so a human (or career-ops)
trims content deliberately.

    python3 scripts/payload_to_typ.py PAYLOAD.json SLUG [--max-pages 1]
        [--order "Aker,Home lab,Vektorprogrammet,Kamy,Skafferiet"]
        [--no-photo] [--no-competencies]

Writes src/cv-SLUG.typ and dist/cv-SLUG.pdf (needs `pip install typst`
or the typst CLI on PATH).
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
DIST = ROOT / "dist"

# Fit ladder: (font size pt, paragraph leading em, list leading em,
# horizontal margin cm, top margin cm, bottom margin cm, entry gap em).
LADDER = [
    (10.0, 0.62, 0.50, 1.7, 1.5, 1.4, 0.32),
    (9.7, 0.58, 0.46, 1.6, 1.3, 1.2, 0.26),
    (9.4, 0.55, 0.44, 1.5, 1.2, 1.1, 0.22),
    (9.1, 0.52, 0.42, 1.4, 1.1, 1.0, 0.18),
]

# Colour palettes: accent (section titles, rules, bullet markers), muted
# (secondary text: employers, dates, contacts), rule (section underline).
PALETTES = {
    "grey":  {"accent": "#1f2328", "muted": "#5f6368", "rule": "#bfc4c9"},
    "blue":  {"accent": "#1d4e89", "muted": "#3d5a7a", "rule": "#b7c9de"},
    "teal":  {"accent": "#0f6466", "muted": "#3a6466", "rule": "#b3d1d1"},
    "plum":  {"accent": "#5b3a87", "muted": "#5a4a72", "rule": "#cbbfdf"},
}

# Typst markup characters that must be escaped in running text.
_SPECIAL = re.compile(r"([\\#$@*_`<>\[\]~])")


def esc(text: str) -> str:
    """Escape plain text for Typst markup (no formatting)."""
    out = _SPECIAL.sub(r"\\\1", text)
    out = out.replace("//", "/\\/")  # `//` would start a comment
    out = re.sub(r"^([-+=/])", r"\\\1", out)  # list / enum / heading markers
    return out


def md_inline(text: str) -> str:
    """Escape text, turning **bold** spans into Typst *bold*."""
    parts = text.split("**")
    rendered = []
    for i, part in enumerate(parts):
        if i % 2 == 1 and part:
            rendered.append("*" + esc(part) + "*")
        else:
            rendered.append(esc(part))
    return "".join(rendered)


def string_literal(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def contact_line(candidate: dict) -> str:
    bits = []
    if candidate.get("phone"):
        bits.append(esc(candidate["phone"]))
    if candidate.get("email"):
        email = candidate["email"]
        bits.append(f'#link({string_literal("mailto:" + email)})[{esc(email)}]')
    for key in ("github", "linkedin", "portfolio"):
        value = candidate.get(key)
        if isinstance(value, dict) and value.get("url"):
            bits.append(f'#link({string_literal(value["url"])})[{esc(value.get("display") or value["url"])}]')
        elif isinstance(value, str) and value:
            bits.append(esc(value))
    return " #h(0.6em)·#h(0.6em) ".join(bits)


def order_experience(items: list[dict], order: list[str]) -> list[dict]:
    if not order:
        return items

    def rank(item: dict) -> int:
        company = item.get("company", "").lower()
        for i, key in enumerate(order):
            if key.lower() in company:
                return i
        return len(order)

    return sorted(items, key=rank)  # stable: unknowns keep payload order


def render(payload: dict, step: tuple, *, photo: bool, competencies: bool, order: list[str],
           palette: str = "blue") -> str:
    size, leading, list_leading, mx, mt, mb, gap = step
    pal = PALETTES[palette]
    c = payload["candidate"]
    sections = payload.get("sections", {})
    lang = payload.get("lang", "en")
    name = c.get("name", "")
    lines: list[str] = []
    w = lines.append

    w("// Generated by scripts/payload_to_typ.py from a career-ops payload. Edit the")
    w("// payload (or rerun career-ops pdf) rather than this file.")
    w(f'#let accent  = rgb("{pal["accent"]}")')
    w(f'#let muted   = rgb("{pal["muted"]}")')
    w(f'#let rulecol = rgb("{pal["rule"]}")')
    w('#let ink     = rgb("#1f2328")')
    w(f'#set document(title: {string_literal(name + ", CV")}, author: {string_literal(name)})')
    w(f'#set page(paper: "a4", margin: (x: {mx}cm, top: {mt}cm, bottom: {mb}cm))')
    w(f'#set text(font: ("Carlito", "Liberation Sans"), size: {size}pt, lang: "{lang}", fill: ink)')
    w(f"#set par(leading: {leading}em, justify: false)")
    # Local helpers: same shapes as _lib.typ, with the palette and fitted spacing.
    w("#let section(title) = {")
    w("  v(0.55em)")
    w("  text(size: 10.5pt, weight: \"bold\", tracking: 0.5pt, fill: accent, upper(title))")
    w("  v(-0.35em)")
    w("  line(length: 100%, stroke: 0.7pt + rulecol)")
    w("  v(0.15em)")
    w("}")
    w("#let edu(what, date) = grid(columns: (1fr, auto), align: (left, right),")
    w("  text(weight: \"bold\")[#what], text(fill: muted)[#date])")
    w("#let entry(role, org: none, date: \"\", body) = {")
    w("  block(breakable: false, width: 100%)[")
    w("    #grid(columns: (1fr, auto), align: (left, right + bottom), column-gutter: 1em,")
    w("      { text(weight: \"bold\")[#role]; if org != none { text(fill: muted)[ · #org] } },")
    w("      text(size: 9pt, fill: muted)[#date])")
    w("    #v(-0.15em)")
    w("    #body")
    w("  ]")
    w(f"  v({gap}em)")
    w("}")
    w("#let pts(..items) = {")
    w("  set list(marker: text(fill: accent)[•], indent: 0.2em, body-indent: 0.45em)")
    w(f"  set par(leading: {list_leading}em)")
    w("  list(..items.pos().map(i => [#i]))")
    w("}")
    w("")

    # Header
    title = md_inline(c.get("title", "")) if c.get("title") else ""
    if photo and (SRC / "photo.png").exists():
        w("#grid(columns: (2.4cm, 1fr), column-gutter: 0.9em, align: (left + horizon, left + horizon),")
        w('  box(clip: true, radius: 4pt, image("photo.png", width: 2.4cm)),')
        w("  [")
        w(f"    #text(size: 21pt, weight: \"bold\")[{esc(name)}]")
        if title:
            w("    #v(-0.55em)")
            w(f"    #text(size: 11.5pt, fill: muted)[{title}]")
        w("  ])")
    else:
        w(f"#text(size: 21pt, weight: \"bold\")[{esc(name)}]")
        if title:
            w("#v(-0.55em)")
            w(f"#text(size: 11.5pt, fill: muted)[{title}]")
    w("#v(0.3em)")
    w(f"#text(size: 9pt, fill: muted)[{contact_line(c)}]")
    w("#v(0.4em)")

    if payload.get("summary"):
        w(md_inline(payload["summary"]))
        w("")
    if competencies and payload.get("competencies"):
        label = sections.get("competencies", "Core competencies")
        items = " · ".join(esc(x) for x in payload["competencies"])
        w(f"#text(size: 9pt, fill: muted)[*{esc(label)}:* {items}]")
        w("")

    exp = order_experience(payload.get("experience", []), order)
    if exp:
        w(f"#section[{esc(sections.get('experience', 'Experience'))}]")
        for e in exp:
            org_bits = [e.get("company", "")]
            if e.get("location"):
                org_bits.append(e["location"])
            org = esc(", ".join(b for b in org_bits if b))
            w(f"#entry(org: [{org}], date: [{esc(e.get('dates', ''))}])[{md_inline(e.get('role', ''))}][")
            bullets = e.get("bullets") or []
            if bullets:
                w("  #pts(" + ", ".join(f"[{md_inline(b)}]" for b in bullets) + ")")
            w("]")

    projects = payload.get("projects") or []
    if projects:
        w(f"#section[{esc(sections.get('projects', 'Projects'))}]")
        for p in projects:
            bullets = [md_inline(b) for b in (p.get("bullets") or [])]
            if p.get("description"):
                desc = md_inline(p["description"])
                if p.get("tech"):
                    desc += " " + esc(f"({p['tech']})")
                bullets.insert(0, desc)
            elif p.get("tech"):
                bullets.append(esc(p["tech"]))
            body = "#pts(" + ", ".join(f"[{b}]" for b in bullets) + ")" if bullets else ""
            w(f"#entry(org: [{esc(p.get('badge', ''))}], date: [{esc(p.get('dates', ''))}])[{esc(p.get('name', ''))}][{body}]")

    skills = payload.get("skills") or []
    if skills:
        w(f"#section[{esc(sections.get('skills', 'Skills'))}]")
        w("#pts(" + ", ".join(
            f"[*{esc(s.get('category', ''))}:* {md_inline(s.get('items', ''))}]" for s in skills
        ) + ")")

    education = payload.get("education") or []
    if education:
        w(f"#section[{esc(sections.get('education', 'Education'))}]")
        for ed in education:
            what = ed.get("title", "")
            org = ", ".join(x for x in (ed.get("org"), ed.get("location")) if x)
            label = esc(what + (" · " + org if org else ""))
            w(f"#edu[{label}][{esc(ed.get('year', ''))}]")
    return "\n".join(lines) + "\n"


def compile_pdf(typ: Path, pdf: Path) -> int:
    """Compile and return the page count."""
    pdf.parent.mkdir(parents=True, exist_ok=True)
    try:
        import typst  # type: ignore

        typst.compile(str(typ), output=str(pdf), root=str(ROOT))
    except ImportError:
        if not shutil.which("typst"):
            sys.exit("payload_to_typ: neither the typst Python package nor the typst CLI is available")
        subprocess.run(["typst", "compile", "--root", str(ROOT), str(typ), str(pdf)], check=True)
    data = pdf.read_bytes()
    return max(1, len(re.findall(rb"/Type\s*/Page[^s]", data)))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("payload", type=Path)
    ap.add_argument("slug", help="output name: src/cv-SLUG.typ, dist/cv-SLUG.pdf")
    ap.add_argument("--max-pages", type=int, default=1)
    ap.add_argument("--order", default="", help="comma-separated company keys, in display order")
    ap.add_argument("--no-photo", action="store_true")
    ap.add_argument("--no-competencies", action="store_true")
    ap.add_argument("--palette", choices=sorted(PALETTES), default="blue")
    args = ap.parse_args()

    if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", args.slug):
        sys.exit("payload_to_typ: slug must be lowercase letters, digits and hyphens")
    payload = json.loads(args.payload.read_text(encoding="utf-8"))
    order = [x.strip() for x in args.order.split(",") if x.strip()]
    typ = SRC / f"cv-{args.slug}.typ"
    pdf = DIST / f"cv-{args.slug}.pdf"

    pages = None
    for level, step in enumerate(LADDER):
        typ.write_text(render(payload, step, photo=not args.no_photo,
                              competencies=not args.no_competencies, order=order,
                              palette=args.palette), encoding="utf-8")
        pages = compile_pdf(typ, pdf)
        if pages <= args.max_pages:
            print(json.dumps({"typ": str(typ), "pdf": str(pdf), "pages": pages,
                              "fit_level": level, "font_pt": step[0]}))
            return
    print(json.dumps({"typ": str(typ), "pdf": str(pdf), "pages": pages, "fit_level": len(LADDER) - 1,
                      "error": f"still {pages} pages at the smallest fit step; trim content"}))
    sys.exit(2)


if __name__ == "__main__":
    main()
